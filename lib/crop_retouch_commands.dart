/// FFmpeg argv shared by the device engine and command-level integration tests.
/// PNG batches are bounded to one second and removed after each encoded part.
class CropRetouchCommands {
  static List<String> extract({
    required String input,
    required String pattern,
    required double startSeconds,
    required int frames,
    required int width,
    required int height,
  }) => [
    '-filter_threads',
    '1',
    '-threads',
    '2',
    '-ss',
    startSeconds.toStringAsFixed(6),
    '-i',
    input,
    '-an',
    '-vf',
    'scale=$width:$height:flags=lanczos,setsar=1,fps=30',
    '-pix_fmt',
    'rgb24',
    '-frames:v',
    '$frames',
    '-start_number',
    '0',
    '-threads',
    '2',
    '-y',
    pattern,
  ];
  static List<String> encode({
    required String pattern,
    required String output,
    required int frames,
    bool lossless = false,
  }) => [
    '-filter_threads',
    '1',
    '-threads',
    '2',
    '-framerate',
    '30',
    '-start_number',
    '0',
    '-i',
    pattern,
    '-frames:v',
    '$frames',
    '-an',
    '-c:v',
    lossless ? 'ffv1' : 'libx264',
    if (lossless) ...[
      '-level',
      '3',
    ] else ...[
      '-preset',
      'veryfast',
      '-crf',
      '18',
    ],
    '-pix_fmt',
    lossless ? 'bgr0' : 'yuv420p',
    '-threads',
    '2',
    '-y',
    output,
  ];
  static List<String> mux({
    required String list,
    required String source,
    required String output,
    required double seconds,
    int sourceStartMs = 0,
    bool lossless = false,
  }) => [
    '-f',
    'concat',
    '-safe',
    '0',
    '-i',
    list,
    '-i',
    source,
    '-map',
    '0:v:0',
    '-map',
    '1:a?',
    '-t',
    seconds.toStringAsFixed(6),
    '-c:v',
    'copy',
    if (sourceStartMs == 0) ...[
      '-c:a',
      'copy',
    ] else ...[
      '-filter:a',
      'atrim=start=${sourceStartMs / 1000}:duration=$seconds,asetpts=PTS-STARTPTS',
      '-c:a',
      'aac',
      '-b:a',
      '128k',
    ],
    if (!lossless) ...['-movflags', '+faststart'],
    '-y',
    output,
  ];
}
