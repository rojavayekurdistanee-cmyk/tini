import 'package:flutter/material.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:provider/provider.dart';
import 'package:intl/intl.dart'; 
import 'package:share_plus/share_plus.dart'; 
import 'package:cloud_functions/cloud_functions.dart';
import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
// الاستدعاء الصحيح للملف مع الـ Alias
import 'package:titi_star/auth_provider.dart' as custom;

/*
  [Tini Project Rules]:
  1. File Name: data_archive_screen.dart
  2. Concept: Automated Data Archive (PDF Export + Server Log).
  3. UI Style: Dark Surface (0xFF1A222C), Background (0xFF0F1720), Teal Accents.
  4. Final Fix: PDF Generation implemented for real file saving.
*/

class DataArchiveScreen extends StatefulWidget {
  const DataArchiveScreen({super.key});

  @override
  State<DataArchiveScreen> createState() => _DataArchiveScreenState();
}

class _DataArchiveScreenState extends State<DataArchiveScreen> {
  bool _isExporting = false;
  final Color bgColor = const Color(0xFF0F1720);
  final Color surfaceColor = const Color(0xFF1A222C);
  final Color titiTeal = Colors.teal;

  // دالة إنشاء ملف الـ PDF وحفظه
  Future<void> _generateAndDownloadPDF(String fullName, String username, String email, String uid, String date) async {
    setState(() => _isExporting = true);

    try {
      // 1. تسجيل العملية في السيرفر (Cloud Function) لتوثيق الطلب
      await FirebaseFunctions.instance
          .httpsCallable('requestUserDataExport')
          .call();

      // 2. بناء محتوى ملف الـ PDF
      final pdf = pw.Document();
      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (pw.Context context) {
            return pw.Padding(
              padding: const pw.EdgeInsets.all(32),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text("Tini - User Data Archive", 
                      style: pw.TextStyle(fontSize: 26, fontWeight: pw.FontWeight.bold, color: PdfColors.teal)),
                  pw.SizedBox(height: 10),
                  pw.Divider(thickness: 2, color: PdfColors.grey),
                  pw.SizedBox(height: 30),
                  _buildPdfRow("Full Name:", fullName),
                  _buildPdfRow("Username:", "@$username"),
                  _buildPdfRow("Email Address:", email),
                  _buildPdfRow("User ID (UID):", uid),
                  _buildPdfRow("Joined Date:", date),
                  pw.SizedBox(height: 50),
                  pw.Divider(color: PdfColors.grey300),
                  pw.Text("Generated on: ${DateFormat('yyyy/MM/dd HH:mm').format(DateTime.now())}", 
                      style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
                  pw.SizedBox(height: 5),
                  pw.Text("This is an official data export file generated by Tini system.", 
                      style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
                ],
              ),
            );
          },
        ),
      );

      // 3. تحويل الملف إلى Bytes وعرض نافذة الحفظ/الطباعة
      final Uint8List bytes = await pdf.save();
      await Printing.layoutPdf(
        onLayout: (PdfPageFormat format) async => bytes,
        name: 'TitiStar_Archive_${username}.pdf',
      );

    } catch (e) {
      debugPrint("PDF/Server Error: $e");
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text("حدث خطأ أثناء تصدير الملف: $e")),
        );
      }
    } finally {
      if (mounted) setState(() => _isExporting = false);
    }
  }

  // مساعد لبناء الأسطر داخل الـ PDF
  pw.Widget _buildPdfRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 8),
      child: pw.Row(
        children: [
          pw.Text("$label ", style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 14)),
          pw.Text(value, style: const pw.TextStyle(fontSize: 14)),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    // استدعاء البروفايدر باستخدام النوع الصريح والـ Alias
    final auth = Provider.of<custom.AuthProvider>(context);
    final User? user = FirebaseAuth.instance.currentUser;

    String joinedDate = user?.metadata.creationTime != null 
        ? DateFormat('yyyy/MM/dd').format(user!.metadata.creationTime!) 
        : "غير متوفر";

    return Scaffold(
      backgroundColor: bgColor,
      appBar: AppBar(
        backgroundColor: bgColor,
        elevation: 0,
        centerTitle: true,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios_new, color: Colors.white, size: 20),
          onPressed: () => Navigator.pop(context),
        ),
        title: const Text(
          "أرشيف البيانات",
          style: TextStyle(color: Colors.white, fontSize: 17, fontWeight: FontWeight.bold),
        ),
      ),
      body: Padding(
        padding: const EdgeInsets.symmetric(horizontal: 20.0),
        child: Column(
          children: [
            const SizedBox(height: 20),
            const Icon(Icons.picture_as_pdf_rounded, color: Colors.teal, size: 70),
            const SizedBox(height: 15),
            const Text(
              "أرشيفك الرقمي جاهز",
              style: TextStyle(color: Colors.white, fontSize: 18, fontWeight: FontWeight.bold),
            ),
            const SizedBox(height: 10),
            const Text(
              "بإمكانك تحميل نسخة كاملة من بياناتك المسجلة لدينا في ملف PDF مرتب وجاهز للطباعة.",
              textAlign: TextAlign.center,
              style: TextStyle(color: Colors.grey, fontSize: 13),
            ),
            const SizedBox(height: 30),
            
            Expanded(
              child: Container(
                padding: const EdgeInsets.all(20),
                decoration: BoxDecoration(
                  color: surfaceColor,
                  borderRadius: BorderRadius.circular(20),
                ),
                child: ListView(
                  children: [
                    _buildInfoRow("الاسم الكامل", auth.fullName),
                    _buildInfoRow("اسم المستخدم", "@${auth.username}"),
                    _buildInfoRow("البريد الإلكتروني", auth.email),
                    _buildInfoRow("تاريخ الانضمام", joinedDate),
                  ],
                ),
              ),
            ),

            const SizedBox(height: 25),

            SizedBox(
              width: double.infinity,
              height: 55,
              child: ElevatedButton(
                style: ElevatedButton.styleFrom(
                  backgroundColor: titiTeal,
                  shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
                ),
                onPressed: _isExporting ? null : () => _generateAndDownloadPDF(
                  auth.fullName, 
                  auth.username, 
                  auth.email, 
                  user?.uid ?? "", 
                  joinedDate
                ),
                child: _isExporting 
                    ? const SizedBox(
                        height: 20,
                        width: 20,
                        child: CircularProgressIndicator(color: Colors.white, strokeWidth: 2),
                      )
                    : const Text(
                        "تحميل ملف PDF", 
                        style: TextStyle(color: Colors.white, fontSize: 16, fontWeight: FontWeight.bold),
                      ),
              ),
            ),
            const SizedBox(height: 40),
          ],
        ),
      ),
    );
  }

  Widget _buildInfoRow(String label, String value) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 12.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(label, style: const TextStyle(color: Colors.teal, fontSize: 11, fontWeight: FontWeight.bold)),
          const SizedBox(height: 5),
          Text(value, style: const TextStyle(color: Colors.white, fontSize: 14)),
          const Divider(color: Colors.white10, height: 20),
        ],
      ),
    );
  }
}