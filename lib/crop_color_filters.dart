import 'package:flutter/material.dart';

/// A single affine RGB transform is shared by live preview, thumbnails and
/// FFmpeg export. No source media is changed; intensity blends with identity.
class CropColorFilter {
  final String id, name, category;
  final double saturation, contrast, brightness, red, green, blue;
  const CropColorFilter(
    this.id,
    this.name,
    this.category,
    this.saturation,
    this.contrast,
    this.brightness,
    this.red,
    this.green,
    this.blue,
  );

  List<double> matrix(double intensity) {
    final t = intensity.clamp(0.0, 1.0);
    final gains = [red, green, blue];
    const luma = [.2126, .7152, .0722];
    final result = List<double>.filled(20, 0);
    for (var row = 0; row < 3; row++) {
      for (var col = 0; col < 3; col++) {
        final identity = row == col ? 1.0 : 0.0;
        final value =
            contrast *
            gains[row] *
            (luma[col] * (1 - saturation) + (row == col ? saturation : 0));
        result[row * 5 + col] = identity + (value - identity) * t;
      }
      result[row * 5 + 4] = ((.5 * (1 - contrast) + brightness) * 255) * t;
    }
    result[18] = 1;
    return result;
  }
}

class CropFilterSelection {
  final String? id;
  final double intensity;
  const CropFilterSelection({this.id, this.intensity = 1});
  CropColorFilter? get filter => CropColorFilters.find(id);
  bool get enabled => filter != null && intensity > 0;
  Widget apply(Widget child) => !enabled
      ? child
      : ColorFiltered(
          colorFilter: ColorFilter.matrix(filter!.matrix(intensity)),
          child: child,
        );

  /// Alpha is 1 in gbrap, so ra/ga/ba are the same constant offsets used by
  /// Flutter's 4x5 matrix. Clamp only after the combined RGB transform.
  String get ffmpeg {
    if (!enabled) return 'null';
    final m = filter!.matrix(intensity);
    final options = <String>[];
    const channels = ['r', 'g', 'b'];
    for (var r = 0; r < 3; r++) {
      for (var c = 0; c < 3; c++) {
        options.add(
          '${channels[r]}${channels[c]}=${m[r * 5 + c].toStringAsFixed(9)}',
        );
      }
      options.add('${channels[r]}a=${(m[r * 5 + 4] / 255).toStringAsFixed(9)}');
    }
    return 'format=gbrap,colorchannelmixer=${options.join(':')}';
  }

  @override
  bool operator ==(Object other) =>
      other is CropFilterSelection &&
      id == other.id &&
      intensity == other.intensity;
  @override
  int get hashCode => Object.hash(id, intensity);
}

